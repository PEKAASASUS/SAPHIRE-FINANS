@lru_cache(maxsize=160)
def icon(name,color=MUTED,size=20):
    scale=3
    image=Image.new('RGBA',(size*scale,size*scale))
    draw=ImageDraw.Draw(image)
    factor=size*scale/24
    for points in PATHS.get(name,PATHS['activity']):
        draw.line([(round(x*factor),round(y*factor)) for x,y in points],fill=color,width=max(2,round(1.65*factor)),joint='curve')
    circles={'search':[(3,3,16,16)],'settings':[(9,9,15,15)],'eye':[(9,9,15,15)],'tag':[(7,7,9,9)],'info':[(11,5,13,7)]}
    for bounds in circles.get(name,[]):draw.ellipse([v*factor for v in bounds],outline=color,width=max(2,round(1.65*factor)))
    if name=='more':
        for y in (5,12,19):draw.ellipse([(11*factor,(y-1)*factor),(13*factor,(y+1)*factor)],fill=color)
    return ctk.CTkImage(image,image,size=(size,size))


@lru_cache(maxsize=32)
def shadow_image(width,height,radius=20):
    width,height=max(20,width),max(20,height)
    image=Image.new('RGBA',(width,height))
    mask=Image.new('RGBA',image.size)
    ImageDraw.Draw(mask).rounded_rectangle((10,7,width-10,height-9),radius=radius,fill=(0,0,0,30))
    return mask.filter(ImageFilter.GaussianBlur(9))
